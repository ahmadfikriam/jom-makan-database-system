-- 1. MENU TABLE
CREATE TABLE "MENU" (
    "ITEM_ID" VARCHAR2(10),
    "ITEM_NAME" VARCHAR2(25) CONSTRAINT "MENU_ITEM_NAME_NN" NOT NULL ENABLE,
    "ITEM_PRICE" NUMBER(10,4) CONSTRAINT "MENU_ITEM_PRICE_NN" NOT NULL ENABLE,
    CONSTRAINT "MENU_ITEM_ID_PK" PRIMARY KEY ("ITEM_ID")
);

-- 2. ORDER ITEM TABLE
CREATE TABLE "ORDERITEM" (
    "ORDER_ID" VARCHAR2(10),
    "ORDER_NAME" VARCHAR2(20) CONSTRAINT "ORDERITEM_ORDER_NAME_NN" NOT NULL ENABLE,
    "ORDER_PRICE" NUMBER(10,4) CONSTRAINT "ORDERITEM_ORDER_PRICE_NN" NOT NULL ENABLE,
    "ITEM_ID" VARCHAR2(10),
    CONSTRAINT "ORDERITEM_ORDER_ID_PK" PRIMARY KEY ("ORDER_ID"),
    CONSTRAINT "ORDERITEM_ITEM_ID_FK" FOREIGN KEY ("ITEM_ID") REFERENCES "MENU" ("ITEM_ID") ENABLE
);

-- 3. CUSTOMER TABLE
CREATE TABLE "CUSTOMER" (
    "CUTOMER_ID" VARCHAR2(10),
    "CUSTOMER_FIRST" VARCHAR2(20) CONSTRAINT "CUSTOMER_CUSTOMER_FIRST_NN" NOT NULL ENABLE,
    "CUSTOMER_LAST" VARCHAR2(20) CONSTRAINT "CUSTOMER_CUSTOMER_LAST_NN" NOT NULL ENABLE,
    "CUSTOMER_CONTACT" VARCHAR2(100) CONSTRAINT "CUSTOMER_CUSTOMER_CONTACT_NN" NOT NULL ENABLE,
    "ADDRESS" VARCHAR2(25) CONSTRAINT "CUSTOMER_ADDRESS_NN" NOT NULL ENABLE,
    "ORDER_ID" VARCHAR2(10) NOT NULL ENABLE,
    CONSTRAINT "CUSTOMER_CUSTOMER_ID_PK" PRIMARY KEY ("CUTOMER_ID"),
    CONSTRAINT "CUSTOMER_ORDER_ID_FK" FOREIGN KEY ("ORDER_ID") REFERENCES "ORDERITEM" ("ORDER_ID") ENABLE
);

-- 4. EMPLOYEE TABLE
CREATE TABLE "EMPLOYEE" (
    "EMPLOYEE_ID" VARCHAR2(10 CHAR) NOT NULL ENABLE,
    "EMPLOYEE_FIRSTNAME" VARCHAR2(100 CHAR) NOT NULL ENABLE,
    "EMPLOYEE_LASTNAME" VARCHAR2(100 CHAR) NOT NULL ENABLE,
    "EMPLOYEE_PHONENUMBER" NUMBER NOT NULL ENABLE,
    "EMPLOYEE_DOB" DATE NOT NULL ENABLE,
    "EMPLOYEE_SALARY" VARCHAR2(10 CHAR) NOT NULL ENABLE,
    CONSTRAINT "EMPLOYEE_PK" PRIMARY KEY ("EMPLOYEE_ID")
);
